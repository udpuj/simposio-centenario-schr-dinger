(function initI18nAndNav() {
  const urlParams = new URLSearchParams(window.location.search);
  const queryLang = urlParams.get('lang');
  let currentLang = (queryLang === 'es' || queryLang === 'en')
    ? queryLang
    : (localStorage.getItem('lang') || 'es');

  function applyTranslations(lang) {
    const dict = translations[lang] || translations.es;

    // Translate elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        if (dict[key].includes('<')) {
          el.innerHTML = dict[key];
        } else {
          el.textContent = dict[key];
        }
      }
    });

    // Translate page <title> if data-i18n-title is set on <title> or <html>
    const titleEl = document.querySelector('title[data-i18n]');
    if (titleEl) {
      const key = titleEl.getAttribute('data-i18n');
      if (dict[key]) {
        document.title = dict[key];
      }
    }

    // Update language toggle button label
    const langBtn = document.getElementById('lang-toggle');
    if (langBtn) {
      const langCode = langBtn.querySelector('.lang-code');
      if (langCode) {
        langCode.textContent = lang.toUpperCase();
      }
      langBtn.setAttribute(
        'aria-label',
        lang === 'es' ? 'Switch language to English' : 'Cambiar idioma a Español'
      );
      langBtn.setAttribute(
        'title',
        lang === 'es' ? 'Switch to English (EN)' : 'Cambiar a Español (ES)'
      );
    }

    document.documentElement.lang = lang;
    localStorage.setItem('lang', lang);
  }

  function setupInteractions() {
    applyTranslations(currentLang);

    const langToggle = document.getElementById('lang-toggle');
    if (langToggle) {
      langToggle.addEventListener('click', () => {
        currentLang = currentLang === 'es' ? 'en' : 'es';
        applyTranslations(currentLang);
      });
    }

    const navToggle = document.getElementById('nav-toggle');
    const navMenu = document.getElementById('nav-menu');

    if (navToggle && navMenu) {
      navToggle.addEventListener('click', () => {
        navMenu.classList.toggle('active');
        navToggle.classList.toggle('active');
      });

      document.querySelectorAll('.nav-menu a').forEach(link => {
        link.addEventListener('click', () => {
          navMenu.classList.remove('active');
          navToggle.classList.remove('active');
        });
      });

      document.addEventListener('click', e => {
        if (
          !navMenu.contains(e.target) &&
          !navToggle.contains(e.target) &&
          (!langToggle || !langToggle.contains(e.target))
        ) {
          navMenu.classList.remove('active');
          navToggle.classList.remove('active');
        }
      });
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', setupInteractions);
  } else {
    setupInteractions();
  }
})();
